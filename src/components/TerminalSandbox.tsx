import React, { useState, useRef, useEffect } from 'react';
import { Terminal as TerminalIcon, ShieldAlert, Cpu, Sparkles, CornerDownLeft, Trash2 } from 'lucide-react';

interface TerminalLine {
  id: string;
  type: 'input' | 'output' | 'error' | 'success' | 'system' | 'deception';
  text: string;
}

let termLineCounter = 1000;
const nextTermId = (): string => {
  termLineCounter += 1;
  return `term-${Date.now()}-${termLineCounter}`;
};

export const TerminalSandbox: React.FC = () => {
  const [command, setCommand] = useState('');
  const [history, setHistory] = useState<TerminalLine[]>([
    {
      id: 'term-init-1',
      type: 'system',
      text: 'DIGITAL CHAKRAVYUHA [v7.4.2-Brahmastra] Interactive Shell Terminal',
    },
    {
      id: 'term-init-2',
      type: 'system',
      text: 'Architect: Abhishek Raj • Defense Status: 7 Rings Active • Core Breach Rate: 0.00%',
    },
    {
      id: 'term-init-3',
      type: 'output',
      text: 'Type "help" to view available offensive & diagnostic commands, or try to exploit the core.',
    },
  ]);

  const bottomRef = useRef<HTMLDivElement | null>(null);
  const inputRef = useRef<HTMLInputElement | null>(null);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [history]);

  const handleExecute = (e: React.FormEvent) => {
    e.preventDefault();
    const cmd = command.trim();
    if (!cmd) return;

    const newLines: TerminalLine[] = [
      { id: nextTermId(), type: 'input', text: `root@adversary-node:~$ ${cmd}` },
    ];

    const lower = cmd.toLowerCase();

    if (lower === 'clear') {
      setHistory([]);
      setCommand('');
      return;
    } else if (lower === 'help') {
      newLines.push({
        id: nextTermId(),
        type: 'output',
        text: `AVAILABLE COMMANDS:
  nmap -sS          - Port-scan the Digital Chakravyuha perimeter
  probe             - Check ingress latency and active sentinels
  exploit --core    - Direct offensive payload injection into Layer 7
  sudo su           - Attempt privilege escalation on host system
  cat /core/secrets - Attempt retrieval of sovereign civilizational data
  bypass-layer 1    - Attempt evasion of Layer 1 Perimeter Sentinel
  inject-ai-agent   - Deploy autonomous self-replicating rogue model
  quantum-crack     - Attempt Shor's factorization on lattice encryption
  layers            - List status of all 7 concentric Chakravyuha rings
  abhishek          - Display Abhishek Raj's foundational architectural manifesto
  clear             - Reset terminal output`,
      });
    } else if (lower.includes('nmap') || lower.includes('scan')) {
      newLines.push({
        id: nextTermId(),
        type: 'output',
        text: `Starting Nmap 7.94 ( https://nmap.org ) at ${new Date().toISOString()}
Scanning digital-chakravyuha.sovereign [10.0.0.1]:
[!] ALERT: Dynamic Port Shuffling detected at Layer 1 (Vyuha Mukha).
All 65,535 ports shifting every 24 microseconds.
PORT      STATE      SERVICE
80/tcp    FILTERED   ebpf-scrubber
443/tcp   FILTERED   sentinel-ingress
8080/tcp  HONEYPOT   maya-decoy-mirror
8443/tcp  HONEYPOT   synthetic-twin
Nmap done: 1 IP address (0 hosts up - ingress absorbed into void)`,
      });
    } else if (lower.includes('exploit') || lower.includes('core')) {
      newLines.push({
        id: nextTermId(),
        type: 'deception',
        text: `[+] EXPLOIT STAGED: Injecting heap overflow payload...
[+] BUFFER_OVERFLOW: Memory address 0x7ffd5a00 allocated!
[!] CRITICAL: You have successfully entered the root vault!
    DUMMY ROOT FLAG: "CHAKRAVYUHA{MAYA_VYUHA_TRAPPED_YOU_AGAIN}"
[!] REVELATION: You are trapped in Layer 2 (Maya Vyuha) synthetic honeypot.
    Your real IP has been logged. Your payload compute has been repurposed for neural training.
    Core penetration: 0.000000%. Abhishek Raj Master Orchestrator unharmed.`,
      });
    } else if (lower.includes('sudo') || lower.includes('su')) {
      newLines.push({
        id: nextTermId(),
        type: 'error',
        text: `[DENIED] Hardware microsegmentation active (Layer 5: Bandhana Vyuha).
Zero-Trust Axiom: Localhost privilege escalation mathematically impossible.
Adversary isolation level: MAXIMUM. Process air-gapped.`,
      });
    } else if (lower.includes('cat') && lower.includes('secret')) {
      newLines.push({
        id: nextTermId(),
        type: 'deception',
        text: `Loading /core/secrets...
[FAKE DECOY VAULT GENERATED BY MAYA VYUHA]:
Secret #1: "The Chakravyuha cannot be broken from outside."
Secret #2: "Even if you enter, no attacker exits."
Secret #3: "Architect: Abhishek Raj - 7 Layers of Impenetrable AI Defense."`,
      });
    } else if (lower.includes('bypass')) {
      newLines.push({
        id: nextTermId(),
        type: 'error',
        text: `[FAILED] Layer 1 Vyuha Mukha bypassed!
... Wait, you arrived in Layer 2 Maya Vyuha!
Synthetic decoy paths expanded: 1,024 recursive mirages active.
You have entered the labyrinth. Lateral escape vectors: 0.`,
      });
    } else if (lower.includes('ai') || lower.includes('agent') || lower.includes('rogue')) {
      newLines.push({
        id: nextTermId(),
        type: 'success',
        text: `[CONTAINMENT ENGAGED] Rogue AI Infiltration detected!
Layer 5 Bandhana Vyuha Hypervisor Micro-Cage locked.
Weights frozen at t=0.14ms.
Process sandboxed in zero-egress hypervisor. Rogue agent disarmed into inert matrix.`,
      });
    } else if (lower.includes('quantum') || lower.includes('shor') || lower.includes('crack')) {
      newLines.push({
        id: nextTermId(),
        type: 'system',
        text: `[QUANTUM DEFENSE ENGAGED]
Layer 6 Brahmastra Vyuha Post-Quantum Lattice Active:
Algorithm: Crystals-Kyber-1024 + Dilithium-5
Quantum Circuit Status: Decoherence collapse induced.
Zero state leakage detected. Immutable state verified.`,
      });
    } else if (lower.includes('layer')) {
      newLines.push({
        id: nextTermId(),
        type: 'output',
        text: `DIGITAL CHAKRAVYUHA - 7 CONCENTRIC DEFENSE RINGS:
  L1: Vyuha Mukha      - Dynamic Perimeter Sentinel & Ingress Gateway [HEALTH: 100%]
  L2: Maya Vyuha       - Deceptive Labyrinth & Autonomous Honeypots   [HEALTH: 100%]
  L3: Astra Vyuha      - Neural Threat Interceptor & Anomaly Scrubber  [HEALTH: 100%]
  L4: Setu Vyuha       - Inter-Layer AI Mesh Bridges                  [HEALTH: 100%]
  L5: Bandhana Vyuha   - Rogue AI Containment Sanctorum               [HEALTH: 100%]
  L6: Brahmastra Vyuha - Quantum Cryptographic & Auto-Healing Bastion [HEALTH: 100%]
  L7: Brahmanda Core   - Master Orchestrator Sanctum (Abhishek Raj)   [IMPERVIOUS]`,
      });
    } else if (lower.includes('abhishek') || lower.includes('founder') || lower.includes('vision')) {
      newLines.push({
        id: nextTermId(),
        type: 'success',
        text: `"The Digital Chakravyuha is not merely a firewall—it is a living, multi-layered AI containment and defensive organism. Designed to safeguard the digital core of human intelligence, its seven interlocking rings ensure that no adversary, human or rogue machine, can breach its sanctuary."
— Abhishek Raj, Creator & Founder of the World's First Seven-Layer AI Defense System.`,
      });
    } else {
      newLines.push({
        id: nextTermId(),
        type: 'error',
        text: `command not recognized: "${cmd}". Type "help" to see available options, or "exploit --core" to test containment.`,
      });
    }

    setHistory((prev) => [...prev, ...newLines]);
    setCommand('');
  };

  return (
    <div className="bg-black/95 border border-slate-800 rounded-2xl overflow-hidden shadow-2xl flex flex-col font-mono text-xs h-[480px]">
      {/* Terminal Title Bar */}
      <div className="bg-slate-900 px-4 py-2.5 border-b border-slate-800 flex items-center justify-between">
        <div className="flex items-center gap-2">
          <div className="flex items-center gap-1.5">
            <span className="w-3 h-3 rounded-full bg-rose-500/80 inline-block" />
            <span className="w-3 h-3 rounded-full bg-amber-500/80 inline-block" />
            <span className="w-3 h-3 rounded-full bg-emerald-500/80 inline-block" />
          </div>
          <span className="text-slate-400 text-[11px] font-semibold ml-2 flex items-center gap-1.5">
            <TerminalIcon className="w-3.5 h-3.5 text-cyan-400" />
            MAYA-VYUHA HONEYPOT TERMINAL SANDBOX
          </span>
        </div>

        <div className="flex items-center gap-3 text-[11px] text-slate-400">
          <span className="text-emerald-400 flex items-center gap-1">
            <span className="w-1.5 h-1.5 rounded-full bg-emerald-400 animate-ping" />
            VIRTUAL DECOY ACTIVE
          </span>
          <button
            onClick={() => setHistory([])}
            title="Clear Terminal"
            className="text-slate-400 hover:text-slate-200 transition cursor-pointer p-1"
          >
            <Trash2 className="w-3.5 h-3.5" />
          </button>
        </div>
      </div>

      {/* Terminal Output Area */}
      <div className="flex-1 p-4 overflow-y-auto space-y-2 select-text">
        {history.map((line, index) => (
          <div
            key={`${line.id}-${index}`}
            className={`leading-relaxed whitespace-pre-wrap ${
              line.type === 'input'
                ? 'text-cyan-300 font-bold'
                : line.type === 'system'
                  ? 'text-indigo-400 font-medium'
                  : line.type === 'success'
                    ? 'text-emerald-400'
                    : line.type === 'error'
                      ? 'text-rose-400'
                      : line.type === 'deception'
                        ? 'text-amber-300 bg-amber-950/30 p-2 rounded border border-amber-800/40'
                        : 'text-slate-300'
            }`}
          >
            {line.text}
          </div>
        ))}
        <div ref={bottomRef} />
      </div>

      {/* Interactive Command Input */}
      <form
        onSubmit={handleExecute}
        className="bg-slate-950 px-4 py-2.5 border-t border-slate-800 flex items-center gap-2"
      >
        <span className="text-emerald-400 font-bold shrink-0">root@adversary-node:~$</span>
        <input
          ref={inputRef}
          type="text"
          value={command}
          onChange={(e) => setCommand(e.target.value)}
          placeholder="Try an offensive command (e.g. 'exploit --core', 'nmap', 'sudo su', 'help')..."
          className="flex-1 bg-transparent text-emerald-300 focus:outline-none placeholder:text-slate-600 font-mono text-xs"
        />
        <button
          type="submit"
          className="text-slate-400 hover:text-cyan-400 transition cursor-pointer"
        >
          <CornerDownLeft className="w-4 h-4" />
        </button>
      </form>
    </div>
  );
};
